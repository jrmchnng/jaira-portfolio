const websiteModalLink =
    document.getElementById(
        "websiteModalLink"
    );


function openWebsiteProject(
    projectId
) {

    const project =
        websiteProjects[
        projectId
        ];


    if (!project) {
        return;
    }


    if (websiteModalTitle) {

        websiteModalTitle.textContent =
            project.title;

    }


    if (websiteModalAddress) {

        websiteModalAddress.textContent =
            project.address;

    }


    if (websiteModalOverview) {

        websiteModalOverview.textContent =
            project.overview;

    }


    if (websiteModalContribution) {

        websiteModalContribution.innerHTML =
            "";


        project.contribution.forEach(
            (item) => {

                const listItem =
                    document.createElement(
                        "li"
                    );

                listItem.textContent =
                    item;

                websiteModalContribution
                    .appendChild(
                        listItem
                    );

            }
        );

    }


    if (websiteModalTools) {

        websiteModalTools.innerHTML =
            "";


        project.tools.forEach(
            (tool) => {

                const toolTag =
                    document.createElement(
                        "span"
                    );

                toolTag.textContent =
                    tool;

                websiteModalTools
                    .appendChild(
                        toolTag
                    );

            }
        );

    }


    /* Update website screenshot */

    if (websiteModalImage) {

        if (project.image) {

            websiteModalImage.src =
                project.image;

            websiteModalImage.alt =
                `${project.title} website homepage preview`;

            websiteModalImage.style.display =
                "block";

        } else {

            websiteModalImage.removeAttribute(
                "src"
            );

            websiteModalImage.alt =
                "";

            websiteModalImage.style.display =
                "none";

        }

    }


    /* Update live website button */

    if (websiteModalLink) {

        if (project.link) {

            websiteModalLink.href =
                project.link;

            websiteModalLink.textContent =
                "Visit Live Website";

            websiteModalLink
                .classList
                .remove(
                    "disabled-link"
                );

            websiteModalLink
                .removeAttribute(
                    "aria-disabled"
                );

            websiteModalLink
                .removeAttribute(
                    "tabindex"
                );

            websiteModalLink
                .setAttribute(
                    "target",
                    "_blank"
                );

            websiteModalLink
                .setAttribute(
                    "rel",
                    "noopener noreferrer"
                );

        } else {

            websiteModalLink.href =
                "#";

            websiteModalLink.textContent =
                "Live website coming soon";

            websiteModalLink
                .classList
                .add(
                    "disabled-link"
                );

            websiteModalLink
                .setAttribute(
                    "aria-disabled",
                    "true"
                );

            websiteModalLink
                .setAttribute(
                    "tabindex",
                    "-1"
                );

            websiteModalLink
                .removeAttribute(
                    "target"
                );

            websiteModalLink
                .removeAttribute(
                    "rel"
                );

        }

    }


    openPortfolioModal(
        websiteModal
    );

}


