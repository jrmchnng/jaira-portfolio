/* =========================================================
   PORTFOLIO FILTERS
========================================================= */

const portfolioFilters =
    document.querySelectorAll(
        ".portfolio-filter"
    );

const portfolioCategoryBlocks =
    document.querySelectorAll(
        ".portfolio-category-block"
    );

const portfolioResultMessage =
    document.getElementById(
        "portfolioResultMessage"
    );


function filterPortfolio(category) {

    portfolioCategoryBlocks.forEach(
        (block) => {

            const blockCategory =
                block.dataset.categorySection;

            const shouldShow =
                category === "all" ||
                blockCategory === category;

            block.classList.toggle(
                "category-hidden",
                !shouldShow
            );

        }
    );


    const filterName =
        category === "all"
            ? "all project categories"
            : `${category} projects`;


    if (portfolioResultMessage) {

        portfolioResultMessage.textContent =
            `Showing ${filterName}.`;

    }

}


portfolioFilters.forEach(
    (button) => {

        button.addEventListener(
            "click",
            () => {

                const selectedFilter =
                    button.dataset.filter;


                portfolioFilters.forEach(
                    (filterButton) => {

                        const isActive =
                            filterButton ===
                            button;

                        filterButton
                            .classList
                            .toggle(
                                "active",
                                isActive
                            );

                        filterButton
                            .setAttribute(
                                "aria-pressed",
                                String(isActive)
                            );

                    }
                );


                filterPortfolio(
                    selectedFilter
                );

            }
        );

    }
);


/* =========================================================
   MODAL UTILITIES
========================================================= */

const portfolioModals =
    document.querySelectorAll(
        ".portfolio-modal"
    );

let activePortfolioModal = null;
let previouslyFocusedElement = null;


function openPortfolioModal(modal) {

    if (!modal) {
        return;
    }


    previouslyFocusedElement =
        document.activeElement;

    activePortfolioModal =
        modal;


    modal.classList.add(
        "modal-open"
    );

    modal.setAttribute(
        "aria-hidden",
        "false"
    );


    document.body.classList.add(
        "portfolio-modal-active"
    );


    const closeButton =
        modal.querySelector(
            ".modal-close-button"
        );


    if (closeButton) {
        closeButton.focus();
    }

}


function closePortfolioModal(modal) {

    if (!modal) {
        return;
    }


    modal.classList.remove(
        "modal-open"
    );

    modal.setAttribute(
        "aria-hidden",
        "true"
    );


    document.body.classList.remove(
        "portfolio-modal-active"
    );


    activePortfolioModal = null;


    if (
        previouslyFocusedElement &&
        typeof previouslyFocusedElement.focus ===
        "function"
    ) {

        previouslyFocusedElement.focus();

    }

}


document
    .querySelectorAll(
        "[data-close-modal]"
    )
    .forEach(
        (element) => {

            element.addEventListener(
                "click",
                () => {

                    const modal =
                        element.closest(
                            ".portfolio-modal"
                        );

                    closePortfolioModal(
                        modal
                    );

                }
            );

        }
    );


