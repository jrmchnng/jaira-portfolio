let activeGallery = null;
let activeGalleryIndex = 0;


/* =========================================================
   RENDER GRAPHIC GALLERY
========================================================= */

function renderGallery() {

    if (
        !activeGallery ||
        !activeGallery.items ||
        !activeGallery.items.length
    ) {
        return;
    }


    const currentItem =
        activeGallery.items[
        activeGalleryIndex
        ];


    if (galleryModalTitle) {

        galleryModalTitle.textContent =
            activeGallery.title;

    }


    if (galleryCounter) {

        galleryCounter.textContent =
            `${activeGalleryIndex + 1} of ${activeGallery.items.length}`;

    }


    if (galleryImageTitle) {

        galleryImageTitle.textContent =
            currentItem.title;

    }


    if (galleryImageDescription) {

        galleryImageDescription.textContent =
            currentItem.description;

    }


    /* Actual gallery image */

    if (galleryImage) {

        galleryImage.src =
            currentItem.image;

        galleryImage.alt =
            currentItem.title;

    }


    /*
     * Keep old placeholder element supported.
     * This prevents errors if it is still present
     * in your HTML while you are updating the modal.
     */

    if (galleryPlaceholderNumber) {

        galleryPlaceholderNumber.textContent =
            String(
                activeGalleryIndex + 1
            ).padStart(
                2,
                "0"
            );

    }


    /* Gallery thumbnails */

    if (!galleryThumbnails) {
        return;
    }


    galleryThumbnails.innerHTML = "";


    activeGallery.items.forEach(
        (item, index) => {

            const thumbnail =
                document.createElement(
                    "button"
                );


            thumbnail.type =
                "button";

            thumbnail.className =
                "gallery-thumbnail";


            /*
             * If actual gallery images are available,
             * show thumbnail previews.
             */

            if (item.image) {

                const thumbnailImage =
                    document.createElement(
                        "img"
                    );

                thumbnailImage.src =
                    item.image;

                thumbnailImage.alt = "";

                thumbnailImage.loading =
                    "lazy";

                thumbnail.appendChild(
                    thumbnailImage
                );

            } else {

                /*
                 * Fallback keeps your old numbered
                 * thumbnail style working.
                 */

                thumbnail.textContent =
                    String(
                        index + 1
                    ).padStart(
                        2,
                        "0"
                    );

            }


            thumbnail.setAttribute(
                "aria-label",
                `View ${item.title}`
            );


            if (
                index ===
                activeGalleryIndex
            ) {

                thumbnail.classList.add(
                    "active"
                );

            }


            thumbnail.addEventListener(
                "click",
                () => {

                    activeGalleryIndex =
                        index;

                    renderGallery();

                }
            );


            galleryThumbnails.appendChild(
                thumbnail
            );

        }
    );

}


/* =========================================================
   NEXT / PREVIOUS GALLERY ITEM
========================================================= */

function showNextGalleryItem() {

    if (
        !activeGallery ||
        !activeGallery.items.length
    ) {
        return;
    }


    activeGalleryIndex =
        (
            activeGalleryIndex +
            1
        ) %
        activeGallery.items.length;


    renderGallery();

}


function showPreviousGalleryItem() {

    if (
        !activeGallery ||
        !activeGallery.items.length
    ) {
        return;
    }


    activeGalleryIndex =
        (
            activeGalleryIndex -
            1 +
            activeGallery.items.length
        ) %
        activeGallery.items.length;


    renderGallery();

}


