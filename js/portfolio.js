document
    .querySelectorAll(
        ".website-card"
    )
    .forEach(
        (card) => {

            const detailsButton =
                card.querySelector(
                    ".website-details-button"
                );


            if (!detailsButton) {
                return;
            }


            card.setAttribute(
                "tabindex",
                "0"
            );

            card.setAttribute(
                "role",
                "button"
            );


            card.addEventListener(
                "click",
                (event) => {

                    /*
                     * Keep live-site links
                     * working normally.
                     */

                    if (
                        event.target.closest(
                            ".portfolio-icon-link"
                        )
                    ) {
                        return;
                    }


                    openWebsiteProject(
                        detailsButton
                            .dataset
                            .project
                    );

                }
            );


            card.addEventListener(
                "keydown",
                (event) => {

                    if (
                        event.key !== "Enter" &&
                        event.key !== " "
                    ) {
                        return;
                    }


                    /*
                     * Do not activate card
                     * when a nested link or
                     * button has focus.
                     */

                    if (
                        event.target.closest(
                            "a, button"
                        )
                    ) {
                        return;
                    }


                    event.preventDefault();


                    openWebsiteProject(
                        detailsButton
                            .dataset
                            .project
                    );

                }
            );

        }
    );


