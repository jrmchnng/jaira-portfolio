/* =========================================================
   MOBILE SWIPE FOR GALLERY
========================================================= */

let galleryTouchStartX = 0;
let galleryTouchEndX = 0;


if (galleryImageButton) {

    galleryImageButton.addEventListener(
        "touchstart",
        (event) => {

            galleryTouchStartX =
                event.changedTouches[0]
                    .screenX;

        },
        {
            passive: true
        }
    );


    galleryImageButton.addEventListener(
        "touchend",
        (event) => {

            galleryTouchEndX =
                event.changedTouches[0]
                    .screenX;


            const swipeDistance =
                galleryTouchEndX -
                galleryTouchStartX;


            if (
                Math.abs(
                    swipeDistance
                ) < 45
            ) {
                return;
            }


            if (
                swipeDistance < 0
            ) {

                showNextGalleryItem();

            } else {

                showPreviousGalleryItem();

            }

        },
        {
            passive: true
        }
    );

}


